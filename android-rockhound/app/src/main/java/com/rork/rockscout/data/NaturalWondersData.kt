    fun byType(type: WonderType): List<NaturalWonder> = allWonders.filter { it.type == type }
    fun byId(id: String): NaturalWonder? = allWonders.firstOrNull { it.id == id }
    fun search(query: String): List<NaturalWonder> {
        val q = query.lowercase().trim()
        if (q.isBlank()) return allWonders
        return allWonders.filter {
            it.name.lowercase().contains(q) ||
                it.location.lowercase().contains(q) ||
                it.description.lowercase().contains(q) ||
                it.rocksToFind.any { rock -> rock.lowercase().contains(q) }
        }
    }
