    /** Returns the background URL for a given achievement, or null if none is set. */
    fun urlFor(achievement: Achievement): String? {
        val index = AchievementCatalog.all.indexOf(achievement)
        if (index < 0 || urls.isEmpty()) return null
        return urls[index % urls.size]
    }

    /** Distinct generated mineral backgrounds for the Player Card XP bars, stat pills, and streak card. */
    val profileTileUrls = ProfileTileUrls(
        fieldCaptureXp = profileUrl(0),
        premiumReferralXp = profileUrl(1),
        identifiedStat = profileUrl(2),
        capturedStat = profileUrl(3),
        badgesStat = profileUrl(4),
        streakStat = profileUrl(5),
        dailyStreak = profileUrl(6),
    )

    /**
     * Safe accessor for the profile-tile background URLs. The catalog ships 100
     * achievement backgrounds (indices 0..99); the profile tiles reuse a fixed
     * slice. If the URL list ever shrinks below what we need, we wrap around so
     * we never throw IndexOutOfBoundsException at object-init time (which would
     * crash every screen that touches [AchievementBackgrounds]).
     */
    private fun profileUrl(slot: Int): String =
        if (urls.isEmpty()) "" else urls[slot % urls.size]

    data class ProfileTileUrls(
        val fieldCaptureXp: String,
        val premiumReferralXp: String,
        val identifiedStat: String,
        val capturedStat: String,
        val badgesStat: String,
        val streakStat: String,
        val dailyStreak: String,
    )
}
