    /**
     * Returns international locations within [MAX_RADIUS_MILES] of the given
     * coordinates. Uses the Haversine formula for accurate great-circle distance.
     * Returns an empty list if no locations are within range.
     */
    fun nearbyInternational(lat: Double, lng: Double): List<Pair<DigLocation, Double>> {
        return internationalLocations.mapNotNull { loc ->
            val dist = AppRepository.distanceMiles(lat, lng, loc.latitude, loc.longitude)
            if (dist <= MAX_RADIUS_MILES) loc to dist else null
        }.sortedBy { it.second }
    }

    /**
     * Determines whether the given coordinates are within the United States
     * (including Alaska and Hawaii). Uses a bounding box check — sufficient
     * for deciding whether to show the full US list or a dynamic international list.
     */
    fun isInUnitedStates(lat: Double, lng: Double): Boolean {
        // Contiguous US + Alaska + Hawaii rough bounding box
        // Alaska: lat 51–71, lng -180 to -130
        // Contiguous: lat 24–50, lng -125 to -66
        // Hawaii: lat 18–22, lng -160 to -154
        return (lat in 24.0..50.0 && lng in -125.0..-66.0) ||
            (lat in 51.0..71.0 && lng in -180.0..-130.0) ||
            (lat in 18.0..22.0 && lng in -160.0..-154.0)
    }
